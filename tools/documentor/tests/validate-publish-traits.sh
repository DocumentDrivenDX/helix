#!/usr/bin/env bash
# Exercise `documentor detect` and `documentor generate` on a fixture repository: traits are detected
# from its files with their evidence, a page the repository's own tool publishes is delegated to
# it, an unclaimed significant file is reported, and a generated page is written from manifests,
# checked by regeneration, and goes stale when a manifest appears (workflows/references/publishing.md, Repository traits).
set -euo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
rg="${DOCUMENTOR:-documentor}"
command -v "$rg" >/dev/null 2>&1 || { echo "FAIL: documentor is not on PATH; run the tests with uv (just test)"; exit 1; }
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }

p="$tmpdir/project"
mkdir -p "$p/docs/helix" "$p/pipelines/claims/bronze_claims/columns" "$p/pipelines/claims/silver_claims/columns" "$p/plugins/review"
printf 'flows:\n  - id: helix\n    root: docs/helix/\npublish:\n  traits: [tablespec-pipeline, plugin-manifests]\n  flows: [data, user]\n' >"$p/.helix.yml"
printf '[project]\nname = "fixture"\ndependencies = ["tablespec"]\n' >"$p/pyproject.toml"
printf 'name: claims\n' >"$p/pipelines/claims/pipeline.yaml"
printf 'table_name: bronze_claims\nprimary_key: [ClaimID]\nconfig_data:\n  source: {file_type: csv, landing: claims-drop}\n  ingestion: {mode: append}\n' >"$p/pipelines/claims/bronze_claims/table.yaml"
printf 'table_name: silver_claims\nconfig_data:\n  transform:\n    depends_on: [bronze_claims]\n' >"$p/pipelines/claims/silver_claims/table.yaml"
for c in ClaimID Amount; do printf 'column:\n  name: %s\n' "$c" >"$p/pipelines/claims/bronze_claims/columns/$c.yaml"; done
printf 'column:\n  name: ClaimID\n' >"$p/pipelines/claims/silver_claims/columns/ClaimID.yaml"
printf 'schema_version = 1\n[workflow]\nid = "review"\ntitle = "Claim review"\ndescription = "Reviews a claim."\nareas = ["Billing"]\nmodel = "balanced"\ntools = ["read"]\n[evals]\nsuite = "e.jsonl"\n' >"$p/plugins/review/plugin.toml"
printf 'FROM scratch\n' >"$p/Dockerfile"

# Detection: both traits proposed with their evidence; the Dockerfile is claimed by no trait.
$rg detect --root "$p" >"$tmpdir/detect"
grep -Eq "PROPOSE 1.00  tablespec-pipeline" "$tmpdir/detect" || fail "expected tablespec-pipeline: $(cat "$tmpdir/detect")"
grep -Eq "PROPOSE 1.00  plugin-manifests" "$tmpdir/detect" || fail "expected plugin-manifests"
grep -q "Page delegated: data/tables to tablespec guidebook" "$tmpdir/detect" || fail "expected the tables page delegated to the guidebook"
grep -q "Page added: user/workflows (reference, generated by plugin-workflows)" "$tmpdir/detect" || fail "expected the generated workflows page"
grep -A3 "no proposed trait claims" "$tmpdir/detect" | grep -q "Dockerfile" || fail "expected the Dockerfile as unmapped"

# Generation: the page holds what the manifests say, with glob sources stamped.
w="$p/docs/guide/user/workflows.md"
$rg generate plugin-workflows --page "$w" --root "$p" --flow user --title Workflows >/dev/null
grep -Eq "^<!-- helix:source plugins/\*/plugin.toml sha256:[0-9a-f]{16} -->" "$w" || fail "expected a stamped glob source: $(head -4 "$w")"
grep -q '| \*\*Claim review\*\* | Billing | Reviews a claim. | balanced | 1 |' "$w" || fail "expected the workflow row: $(cat "$w")"
$rg check-pages "$p/docs/guide" --root "$p" >"$tmpdir/out" 2>&1 || fail "the generated page should pass: $(cat "$tmpdir/out")"
grep -q "unmapped" "$tmpdir/out" && fail "files a generated page reads are documented: $(cat "$tmpdir/out")"

# A new plug-in makes the page stale, naming the command that regenerates it.
mkdir -p "$p/plugins/intake"
printf 'schema_version = 1\n[workflow]\nid = "intake"\ntitle = "Intake"\ndescription = "Takes a request."\nareas = ["General"]\nmodel = "quick"\ntools = []\n' >"$p/plugins/intake/plugin.toml"
$rg check-pages "$p/docs/guide" --root "$p" >"$tmpdir/out" 2>&1 && fail "a new manifest should stale the page"
grep -Eq "^BLOCKING +stale .*workflows.md +its sources changed; run .documentor generate plugin-workflows" "$tmpdir/out" || fail "expected stale: $(cat "$tmpdir/out")"
$rg generate plugin-workflows --page "$w" --root "$p" --flow user --title Workflows >/dev/null
grep -q '| \*\*Intake\*\* |' "$w" || fail "the regenerated page should list the new workflow"
$rg check-pages "$p/docs/guide" --root "$p" >/dev/null 2>&1 || fail "a regenerated page should pass"

echo "OK: documentor detect proposes traits with evidence, delegates pages a repository tool already publishes, and reports unclaimed files; documentor generate writes pages from manifests that the check keeps current"
